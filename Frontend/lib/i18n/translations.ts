// Get the current language, return the translation function
let currentLang: 'en' | 'sw' = 'en';

export function setLanguage(lang: 'en' | 'sw') {
  currentLang = lang;
}

export function getLanguage(): 'en' | 'sw' {
  return currentLang;
}

export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  const dict = currentLang === 'sw' ? SW : EN;
  let val = dict[key] ?? EN[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      val = val.replace(`{${k}}`, String(v));
    }
  }
  return val;
}

